def escape(x):
    if x is None:return '--'
    if isinstance(x,float):return f'{x:.4g}'
    return str(x).replace('_',r'\_').replace('%',r'\%')


def write(name,title,body,date):
    body='\n'.join(line.rstrip() for line in body.splitlines())
    (ROOT/name).write_text(PRE+r'\title{'+title+r'}\author{}\date{'+date+r'}\maketitle'+'\n'+body+'\n'+r'\end{document}'+'\n')


def table(rows,columns):
    text=r'\begin{center}\small\resizebox{\linewidth}{!}{\begin{tabular}{'+'l'*len(columns)+r'}\toprule'+'\n'
    text+=' & '.join(label for _,label in columns)+r'\\\midrule'+'\n'
    for row in rows:text+=' & '.join(escape(row.get(key)) for key,_ in columns)+r'\\'+'\n'
    return text+r'\bottomrule\end{tabular}}\end{center}'+'\n'


