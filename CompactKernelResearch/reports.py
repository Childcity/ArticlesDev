def table(rows,columns):
    text='\\begin{center}\\small\\resizebox{\\linewidth}{!}{\\begin{tabular}{'+'l'*len(columns)+'}\\toprule\n'
    text+=' & '.join(label for _,label in columns)+r'\\\midrule'+'\n'
    for row in rows:
        values=[]
        for key,_ in columns:
            v=row.get(key,'--')
            values.append(f'{v:.4g}' if isinstance(v,float) else str(v).replace('_',r'\_'))
        text+=' & '.join(values)+r'\\'+'\n'
    return text+r'\bottomrule\end{tabular}}\end{center}'

